#!/usr/bin/env python3
"""Rewrite helm-charts/zot/cidrs.json from the live nodes.

Reads the node objects through the Kubernetes MCP client. One
/32 per node: the base address of the node pod CIDR. Run this
script when a node joins the cluster or leaves the cluster.
"""

import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CHART_DIR = ROOT / "helm-charts" / "zot"


def cidrs():
    mcp = Path.home() / "workspace/custom-skills/local-mcp/bin/mcp-cli"
    calls = json.dumps(
        [{"name": "resources_list", "arguments": {"apiVersion": "v1", "kind": "Node"}}]
    )
    out = subprocess.run(
        [str(mcp), "call-tools", "--endpoint", "k8s", "--calls-json", calls],
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    names = sorted(set(re.findall(r'"Name":\s*"([^"]+)"', out)))
    if not names:
        raise SystemExit("error: node list came back empty")
    # resources_list does not carry podCIDR; read each node object.
    result = []
    for name in names:
        calls = json.dumps(
            [
                {
                    "name": "resources_get",
                    "arguments": {"apiVersion": "v1", "kind": "Node", "name": name},
                }
            ]
        )
        out = subprocess.run(
            [str(mcp), "call-tools", "--endpoint", "k8s", "--calls-json", calls],
            capture_output=True,
            text=True,
            check=True,
        ).stdout
        m = re.search(r'"podCIDR":\s*"([0-9.]+)/(\d+)"', out)
        if not m:
            raise SystemExit(f"error: no podCIDR found for node {name}")
        result.append(
            {
                "node": name,
                "podCIDR": f"{m.group(1)}/{m.group(2)}",
                "cidr": f"{m.group(1)}/32",
            }
        )
    doc = {
        "comment": (
            "Generated by hack/zot-cidrs.py from the live "
            "node objects. One /32 per node: the base address of the node pod CIDR."
        ),
        "nodes": result,
    }
    (CHART_DIR / "cidrs.json").write_text(json.dumps(doc, indent=2) + "\n")
    print(f"cidrs: wrote {len(result)} entries")


def main():
    cidrs()
    return 0


if __name__ == "__main__":
    sys.exit(main())
